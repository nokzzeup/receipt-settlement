_TEXT_HEIGHT = 24


def _bbox(x: int, y: int, w: int) -> tuple[tuple[float, float], ...]:
    h = _TEXT_HEIGHT
    return ((x, y), (x + w, y), (x + w, y + h), (x, y + h))


class MockOcrEngine(OcrEngine):
    name = "mock"

    def recognize(self, image_bytes: bytes) -> OcrRawResult:
        # 호출할 때마다 새 객체 → 호출자가 결과를 수정해도 샘플 원본은 그대로
        return OcrRawResult(
            engine=self.name,
            lines=[
                OcrLine(text=text, confidence=conf, bbox=_bbox(x, y, w))
                for text, x, y, w, conf in _SAMPLE
            ],
        )
